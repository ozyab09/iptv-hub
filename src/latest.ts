/**
 * Guard от внепорядочных ответов (гонка async): каждая новая задача
 * инвалидирует предыдущие. begin() возвращает проверку актуальности;
 * если на момент resolve задача уже не актуальна — результат выбрасывается.
 * Чистая логика без DOM/fetch — тестируется в node (принцип проекта).
 *
 * Применение — подмена данных чужим ответом: открытый позже плейлист/EPG
 * должен выигрывать у медленного ответа предыдущего (issue #112).
 */
export class LatestGuard {
  private epoch = 0;

  /** Начать новую актуальную задачу; предыдущие становятся неактуальными. */
  begin(): { isCurrent(): boolean } {
    const epoch = ++this.epoch;
    return {
      isCurrent: (): boolean => this.epoch === epoch,
    };
  }
}
